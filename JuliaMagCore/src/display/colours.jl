# Linear blend between the stops, at `t` in 0 to 1.
function blend_stops(stops, t::Float64)::NTuple{3,UInt8}
    k = 1
    while k < length(stops) - 1 && t > stops[k+1][1]
        k += 1
    end
    t0, c0 = stops[k]
    t1, c1 = stops[k+1]
    f = clamp((t - t0) / (t1 - t0), 0.0, 1.0)
    ch(i) = round(UInt8, clamp(c0[i] + (c1[i] - c0[i]) * f, 0.0, 255.0))
    return (ch(1), ch(2), ch(3))
end

# HSV with full saturation and value, hue in degrees.
function hsv_full(hue::Float64)::NTuple{3,UInt8}
    h = hue / 60
    x = 1 - abs(mod(h, 2) - 1)
    r, g, b = h < 1 ? (1.0, x, 0.0) : h < 2 ? (x, 1.0, 0.0) : h < 3 ? (0.0, 1.0, x) :
              h < 4 ? (0.0, x, 1.0) : h < 5 ? (x, 0.0, 1.0) : (1.0, 0.0, x)
    return (round(UInt8, 255r), round(UInt8, 255g), round(UInt8, 255b))
end

const COLOUR_TABLE_CACHE = Dict{String,Vector{NTuple{3,UInt8}}}()
const COLOUR_TABLE_LOCK = ReentrantLock()

function make_colour_table(name::AbstractString)::Vector{NTuple{3,UInt8}}
    ts = [(k - 1) / 255 for k in 1:256]
    name == "geosoft" && return [blend_stops(GEOSOFT_STOPS, t) for t in ts]
    name == "viridis" && return copy(VIRIDIS_256)
    name == "turbo" && return copy(TURBO_256)
    name == "rainbow" && return [hsv_full(240 * (1 - t)) for t in ts]
    name == "blue-red" && return [blend_stops(BLUE_RED_STOPS, t) for t in ts]
    name == "grey" && return [(UInt8(k - 1), UInt8(k - 1), UInt8(k - 1)) for k in 1:256]
    throw(ArgumentError("the colour table \"$name\" is not known"))
end

"""
    colour_table(name) -> Vector{NTuple{3,UInt8}}

The 256 colours of the table `name` (see `colour_tables`), from low to high.
Throws `ArgumentError` for an unknown name. Tables are built once and shared, so
do not change the result.
"""
function colour_table(name::AbstractString)::Vector{NTuple{3,UInt8}}
    lock(COLOUR_TABLE_LOCK) do
        get!(() -> make_colour_table(name), COLOUR_TABLE_CACHE, String(name))
    end
end

"""
    colour_position(v, lo, hi, table) -> Float32

Where `v` falls on a colour table, from 0 to 1. `NaN` for a `NaN` value, 0.5 when the
limits are equal or `NaN`. `table` is an equalization table (see `equalize_table`) or
`nothing` for a linear stretch.
"""
function colour_position(v::Real, lo::Real, hi::Real, table::Union{Nothing,AbstractVector{Float32}})::Float32
    isnan(v) && return NaN32
    (isnan(lo) || isnan(hi) || lo == hi) && return 0.5f0
    t = clamp((Float64(v) - lo) / (Float64(hi) - lo), 0.0, 1.0)
    table === nothing && return Float32(t)
    x = t * (length(table) - 1)
    i = min(floor(Int, x), length(table) - 2)
    f = Float32(x - i)
    return table[i+1] + (table[i+2] - table[i+1]) * f
end

"""
    effective_style(layer, grid_style, app_colours) -> LayerStyle

The style a layer is drawn with. A layer with its own style, or without a grid style,
uses `layer.style`. Else the style comes from the grid's own style. A grid style that
still has the stock colour table uses `app_colours`, the app's "Grid colours" setting.
"""
function effective_style(layer::MapLayer, grid_style::Union{Nothing,GridStyle}, app_colours::AbstractString)::LayerStyle
    (layer.own_style || grid_style === nothing) && return layer.style
    stock = GridStyle()
    return LayerStyle(;
        colours = grid_style.colours == stock.colours ? String(app_colours) : grid_style.colours,
        stretch = grid_style.method === :linear ? :linear : :histeq,
        min = grid_style.min,
        max = grid_style.max,
        reverse = grid_style.reverse,
        shade = grid_style.shade,
        inclination = grid_style.altitude,
        declination = grid_style.azimuth,
        zfactor = grid_style.zfactor == stock.zfactor ? NaN : grid_style.zfactor,
        resample = layer.style.resample,
    )
end

"The vertical scale of a shaded relief: 2.5 over the mean gradient (Oasis). 1 when there is no gradient."
auto_zfactor(mean_gradient::Real)::Float64 = (isnan(mean_gradient) || !(mean_gradient > 0)) ? 1.0 : 2.5 / mean_gradient

"The unit vector towards the sun, as (east, north, up). The declination is clockwise from north."
function sun_vector(inclination::Real, declination::Real)::NTuple{3,Float64}
    return (cosd(inclination) * sind(declination), cosd(inclination) * cosd(declination), sind(inclination))
end
